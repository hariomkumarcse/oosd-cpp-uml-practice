#include <iostream>
using namespace std;

int main() {
    cout << "Function Overloading Comparison\n\n";

    cout << "C Language:\n";
    cout << "1. Does not support function overloading.\n";
    cout << "2. Different function names are commonly used.\n\n";

    cout << "C++ Language:\n";
    cout << "1. Supports function overloading.\n";
    cout << "2. Functions can share the same name.\n";
    cout << "3. Parameter lists must differ.\n";
    cout << "4. Return type alone cannot distinguish overloads.\n";

    return 0;
}
