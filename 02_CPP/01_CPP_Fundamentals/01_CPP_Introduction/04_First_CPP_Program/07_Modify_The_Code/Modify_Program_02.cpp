#include <iostream>
using namespace std;

int main()
{
	double num1 = 10;
	double num2 = 15;
	double num3 = 20;

	double avg = (num1+num2+num3)/3;

	cout<<"Number 1: " << num1 <<endl;
	cout<<"Number 2: " << num2 <<endl;
	cout<<"Number 3: " << num3 <<endl;
	cout<<"Average: " << avg << endl;

	return 0;
}